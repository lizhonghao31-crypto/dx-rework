import {
  CreateWorkTaskSchema,
  ReviewWholeOrderSchema,
  WholeOrderReviewResponseSchema,
  WorkTaskAssignablePeopleResponseSchema,
} from "@dx-rework/contracts";
import {
  ProcessWorkerPlanResponseSchema,
  SaveProcessWorkerPlanSchema,
} from "@dx-rework/contracts/process-worker-plan";
import { describe, expect, it } from "vitest";

const migratedTailPersonId = "850e82b5-fc66-94fd-203f-a708fe72a9d0";
const orderId = "00000000-0000-4000-8000-000000000010";
const configurationId = "00000000-0000-4000-8000-000000000020";
const configurationItemId = "00000000-0000-4000-8000-000000000021";

describe("business person id contract", () => {
  it("accepts a PostgreSQL UUID generated by migration 0079 without changing the id", () => {
    const parsed = WorkTaskAssignablePeopleResponseSchema.parse({
      people: [{
        personId: migratedTailPersonId,
        displayName: "尾查甲",
        personType: "internal",
        eligibleExecutionKinds: ["tail_inspection"],
      }],
    });
    expect(parsed.people[0]?.personId).toBe(migratedTailPersonId);
  });

  it("keeps duplicate-member validation while accepting migrated business person ids", () => {
    expect(() => CreateWorkTaskSchema.parse({
      expectedOrderVersion: 1,
      configurationItemId,
      mode: "collective",
      members: [{ personId: migratedTailPersonId }, { personId: migratedTailPersonId }],
    })).toThrow();
  });

  it("accepts migrated ids through the N02 preassignment request and response", () => {
    expect(SaveProcessWorkerPlanSchema.parse({
      expectedOrderVersion: 1,
      configurationId,
      expectedConfigurationVersion: 1,
      assignments: [{ configurationItemId, memberIds: [migratedTailPersonId] }],
    }).assignments[0]?.memberIds).toEqual([migratedTailPersonId]);

    expect(ProcessWorkerPlanResponseSchema.parse({
      reworkOrderId: orderId,
      reworkStatus: "pending_process_configuration",
      orderVersion: 1,
      required: true,
      configurationId,
      configurationVersion: 1,
      configurationStatus: "draft",
      assignments: [{
        configurationItemId,
        processName: "尾查",
        executionKind: "tail_inspection",
        members: [{ personId: migratedTailPersonId, displayName: "尾查甲", personType: "internal" }],
      }],
      complete: true,
    }).assignments[0]?.members[0]?.personId).toBe(migratedTailPersonId);
  });

  it("keeps the whole-order personnel chain compatible with the same id", () => {
    expect(ReviewWholeOrderSchema.parse({
      expectedOrderVersion: 2,
      temporaryCoefficients: [{
        configurationItemId,
        personId: migratedTailPersonId,
        multiplier: 1,
      }],
    }).temporaryCoefficients[0]?.personId).toBe(migratedTailPersonId);

    const parsed = WholeOrderReviewResponseSchema.safeParse({
      reworkOrderId: orderId,
      reworkStatus: "in_progress",
      orderVersion: 2,
      canReview: false,
      canAdjustQuantity: false,
    });
    expect(parsed.success).toBe(false);
  });

  it("still rejects malformed business person identifiers", () => {
    expect(() => WorkTaskAssignablePeopleResponseSchema.parse({
      people: [{
        personId: "not-a-postgres-uuid",
        displayName: "异常人员",
        personType: "internal",
        eligibleExecutionKinds: ["worker"],
      }],
    })).toThrow();
  });
});
